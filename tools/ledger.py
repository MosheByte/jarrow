def _pct(part: int, whole: int) -> str:
    if whole == 0:
        return "n/a"
    # Integer inputs and IEEE doubles: the same digits on every platform.
    return f"{100 * part / whole:.1f}%"


def _mib(n: int) -> str:
    return f"{n / (1024 * 1024):.2f} MiB"


def _md(text: str) -> str:
    """Escapes a value for a Markdown table cell."""
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def _table(head: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def _area_status(area: dict[str, Any]) -> str:
    if area["unsupported"] is not None:
        return "unsupported"
    if area["measured"] > 0 and Fraction(area["green"], area["measured"]) >= WORKS_THRESHOLD:
        return "works"
    return "partial"


def _numbers(inputs: dict[str, dict[str, Any] | None]) -> list[list[str]]:
    board, cov, wasm, perf = (inputs[k] for k in ("board", "coverage", "wasm", "perf"))
    rows: list[list[str]] = []

    if board is None:
        rows.append(["Board totals", "not measured yet", "M1: nightly board (convert stubbed); real conversions from M2"])
        rows.append(["Harness pass rate", "not measured yet", "M1: parity harness"])
    else:
        mods = board["mods"]
        totals = (
            f"{board['green']:,} green ({_pct(board['green'], mods)}), "
            f"{board['yellow']:,} yellow ({_pct(board['yellow'], mods)}), "
            f"{board['red']:,} red ({_pct(board['red'], mods)}), "
            f"{board['not_run']:,} not run, of {mods:,} mods"
        )
        rows.append(["Board totals", totals, "nightly board"])
        harness = (
            f"{_pct(board['completed'], board['attempted'])} "
            f"({board['completed']:,} of {board['attempted']:,} runs produced a score)"
        )
        rows.append(["Harness pass rate", harness, "parity harness"])

    if cov is None:
        rows.append(["Fabric API coverage (weighted)", "not measured yet", "M2: rule tables and the Fabric API index"])
    else:
        for v in cov["versions"]:
            value = (
                f"{v['weighted'] * 100:.1f}% weighted; {v['with_rule']:,} of "
                f"{v['symbols']:,} symbols have a rule, {v['tier_b']:,} Tier B, "
                f"{v['unsupported']:,} unsupported"
            )
            rows.append(
                [f"Fabric API coverage, {_md(v['game_version'])} ({_md(v['fabric_api'])})", value, "rule tables"]
            )

    surfaces = {} if perf is None else {s["surface"]: s for s in perf["surfaces"]}
    for surface, label, milestone in (
        ("cli", "Median conversion time, CLI", "M2: CLI in the nightly"),
        ("wasm", "Median conversion time, browser", "M3: crates/wasm in the browser"),
    ):
        s = surfaces.get(surface)
        if s is None:
            rows.append([label, "not measured yet", milestone])
        else:
            value = (
                f"{s['convert_ms_median']:,} ms convert, {s['classify_ms_median']:,} ms "
                f"classify (median of {s['samples']:,}, {_md(s['machine'])})"
            )
            rows.append([label, value, "nightly timings"])

    if wasm is None:
        rows.append(["WASM size (gzipped)", "not measured yet", "M3: crates/wasm"])
    else:
        within = "within" if wasm["gzip_bytes"] <= wasm["budget_gzip_bytes"] else "OVER"
        value = (
            f"{_mib(wasm['gzip_bytes'])} gzipped ({wasm['gzip_bytes']:,} bytes; "
            f"{_mib(wasm['raw_bytes'])} raw), {within} the {_mib(wasm['budget_gzip_bytes'])} budget"
        )
        rows.append(["WASM size (gzipped)", value, f"build of {wasm['commit'][:12]}"])
    return rows


def render(root: Path) -> str:
    """Returns the full text of LEDGER.md for the inputs under ROOT/ledger/inputs/."""
    inputs = load_inputs(root)
    board = inputs["board"]
    out: list[str] = [HEADER, "", "# Ledger", ""]
    out.append(
        "What Jarrow does today, as measured by the nightly board and the parity harness. "
        "Nobody writes this page by hand: the nightly writes `ledger/inputs/*.json` and "
        "`tools/ledger.py` renders it. A claim without a harness result does not appear here."
    )
    out.append("")
    if board is None:
        out.append(f"{NO_NIGHTLY} The first one runs in milestone M1.")
    else:
        versions = ", ".join(board["game_versions"])
        out.append(
            f"Last nightly: `{_md(board['run'])}` on {board['date']}, commit "
            f"`{board['commit'][:12]}`, game versions {_md(versions)}."
        )
    out.append("")

    areas = [] if board is None else board["areas"]
    by_status: dict[str, list[dict[str, Any]]] = {"works": [], "partial": [], "unsupported": []}
    for area in areas:
        by_status[_area_status(area)].append(area)
    threshold = f"{int(WORKS_THRESHOLD * 100)}%"

    out += ["## What works", ""]
    if board is None:
        out.append(
            f"{NO_NIGHTLY} Nothing is listed as working until the harness shows it green; "
            "the first measurements come from the nightly board in milestone M1, and the "
            "first conversions from milestone M2."
        )
    elif not by_status["works"]:
        out.append(f"No area reaches {threshold} green among the mods that exercise it yet.")
    else:
        out.append(f"Areas where at least {threshold} of the measured mods are green.")
        out.append("")
        rows = [
            [_md(a["area"]), f"{a['green']:,} of {a['measured']:,}", _pct(a["green"], a["measured"])]
            for a in by_status["works"]
        ]
        out += _table(["Area", "Green mods", "Share"], rows)
    out.append("")

    out += ["## Partial", ""]
    if board is None:
        out.append(
            f"{NO_NIGHTLY} Partial areas are measured by the harness in the nightly board "
            "(milestone M1 onward)."
        )
    elif not by_status["partial"]:
        out.append("No partial areas in the last nightly.")
    else:
        out.append(f"Areas measured below {threshold} green, or not measured by the harness yet.")
        out.append("")
        rows = []
        for a in by_status["partial"]:
            if a["measured"] == 0:
                rows.append([_md(a["area"]), "not measured", "n/a"])
            else:
                rows.append(
                    [_md(a["area"]), f"{a['green']:,} of {a['measured']:,}", _pct(a["green"], a["measured"])]
                )
        out += _table(["Area", "Green mods", "Share"], rows)
    out.append("")

    out += ["## Unsupported", ""]
    if board is None:
        out.append(
            f"{NO_NIGHTLY} Unsupported areas and their reasons come from the tier classifier "
            "and the board (milestone M1)."
        )
    elif not by_status["unsupported"]:
        out.append("No area is marked unsupported in the last nightly.")
    else:
        rows = [[_md(a["area"]), _md(a["unsupported"])] for a in by_status["unsupported"]]
        out += _table(["Area", "Why"], rows)
    out.append("")

    out += ["## Numbers from the last nightly", ""]
    if all(inputs[k] is None for k in ("board", "coverage", "wasm", "perf")):
        out.append(f"{NO_NIGHTLY} Each number below names the milestone that first produces it.")
        out.append("")
    out += _table(["Number", "Value", "Source"], _numbers(inputs))
    out.append("")

    out += ["## Open red reasons", ""]
    if board is None:
        out.append(
            f"{NO_NIGHTLY} Red reasons are classified from harness logs (milestone M1) and "
            "become the work queue for the rule tables."
        )
    elif board["red"] == 0:
        out.append("No red mods in the last nightly.")
    else:
        reasons = board["red_reasons"]
        shown = reasons[:MAX_RED_REASONS]
        rows = [[_md(r["reason"]), f"{r['count']:,}"] for r in shown]
        if rows:
            out += _table(["Reason", "Red mods"], rows)
            out.append("")
        hidden = reasons[MAX_RED_REASONS:]
        if hidden:
            count = sum(r["count"] for r in hidden)
            out.append(f"And {len(hidden):,} more reasons covering {count:,} red mods.")
            out.append("")
        unclassified = board["red"] - sum(r["count"] for r in reasons)
        if unclassified:
            out.append(f"{unclassified:,} red mods have no classified reason yet.")
            out.append("")
        if out[-1] == "":
            out.pop()
    out.append("")

    out += _contributors_section(inputs["contributors"])
    return "\n".join(out)


def _names(names: list[str]) -> str:
    shown = ", ".join(_md(n) for n in names[:MAX_NAMES])
    hidden = len(names) - MAX_NAMES
    return f"{shown} and {hidden:,} more" if hidden > 0 else shown


def _counted(n: int, one: str, many: str, names: list[str]) -> str:
    text = f"{n:,} {one if n == 1 else many}"
    return f"{text} ({_names(names)})" if names else text


def _contributors_section(data: dict[str, Any] | None) -> list[str]:
    out = ["## Contributors", ""]
    if data is None:
        out.append(
            f"{NO_DATA}. `tools/contributors.py --ledger` writes these numbers in the nightly "
            "contributors workflow."
        )
        out.append("")
        out += _table(
            ["Number", "Value"],
            [["Contributors (30 days)", NO_DATA], ["First-time contributors (30 days)", NO_DATA]],
        )
        out.append("")
        return out
    window = f"the {data['window_days']} days to {data['as_of']} (UTC)"
    if "github-pulls" in data["sources"]:
        source = "merged pull requests (GitHub) and commit authors and co-authors (git)"
    else:
        source = "commit authors and co-authors (git) only; merged pull requests could not be read"
    out.append(f"Who landed work in {window}, from {source}. Bots are not counted.")
    out.append("")
    people, agents = data["people"], data["agents"]
    contributors = (
        f"{_counted(len(people), 'person', 'people', people)}; "
        f"{_counted(len(agents), 'agent', 'agents', agents)}"
    )
    first = data["first_time"]
    if first is None:
        first_text = "not measured: the merged pull request lookup was unavailable"
    else:
        first_text = _counted(len(first), "person", "people", first)
    out += _table(
        ["Number", "Value"],
        [["Contributors (30 days)", contributors], ["First-time contributors (30 days)", first_text]],
    )
    out.append("")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate LEDGER.md from ledger/inputs/.")
    parser.add_argument("--stdout", action="store_true", help="print instead of writing LEDGER.md")
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="repository root (default: the parent of tools/)",
    )
    args = parser.parse_args(argv)
    try:
        text = render(args.root)
    except LedgerInputError as err:
        print(f"ledger: {err}", file=sys.stderr)
        return 1
    data = text.encode("utf-8")
    if args.stdout:
        sys.stdout.buffer.write(data)
        sys.stdout.buffer.flush()
    else:
        (args.root / OUTPUT).write_bytes(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
