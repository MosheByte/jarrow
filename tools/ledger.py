#!/usr/bin/env python3
"""Generate LEDGER.md from the numbers the nightly produces.

LEDGER.md is never edited by hand (a project rule, AGENTS.md). The nightly board writes JSON files
under ledger/inputs/ and runs this script; tools/pr_ready.py fails any change whose
LEDGER.md differs from `python tools/ledger.py --stdout`. The output depends only on the
inputs: no clock, no environment, no network, so two runs give identical bytes.

Usage:
    python tools/ledger.py              write LEDGER.md at the repository root
    python tools/ledger.py --stdout     print it instead
    python tools/ledger.py --root DIR   use another repository root

Every input is optional. A missing file means the number does not exist yet, and the
ledger says so and names the milestone that produces it. Unknown keys and wrong types are
errors, so a typo in the nightly cannot silently drop a number. All counts are
non-negative integers; dates are YYYY-MM-DD (UTC); "schema" is 1 in every file.

ledger/inputs/board-summary.json  (nightly board, from milestone M1)
    {
      "schema": 1,
      "run": "nightly-2026-11-04",           id of the nightly run
      "date": "2026-11-04",
      "commit": "<40 hex chars>",             commit of jarrow the nightly ran
      "game_versions": ["1.21.1", "1.21.11"],
      "mods": 1000,                           mods on the board
      "green": 612, "yellow": 231, "red": 157, "not_run": 0,
                                              outcomes; the four must sum to "mods"
      "harness": {"completed": 1000, "attempted": 1000},
                                              harness runs that produced a score (a red
                                              mod still counts as completed; an
                                              infrastructure failure does not)
      "areas": [                              conversion areas measured by the harness
        {"area": "manifest", "measured": 1000, "green": 990, "unsupported": null}
      ],                                      "measured": board mods exercising the area,
                                              "green": those of them that are green,
                                              "unsupported": null, or the reason the area
                                              is out of scope for v1
      "red_reasons": [                        classified reasons of red mods, one per mod
        {"reason": "mixin target not found", "count": 61}
      ]                                       counts sum to at most "red"
    }

ledger/inputs/coverage.json  (rule tables and the Fabric API index, from milestone M2)
    {
      "schema": 1,
      "date": "2026-11-04",
      "versions": [
        {"game_version": "1.21.1", "fabric_api": "0.116.7+1.21.1",
         "symbols": 5321, "with_rule": 1200, "tier_b": 300, "unsupported": 100,
         "weighted": 0.7412}
      ]                                       "weighted": share of the index covered by
                                              rules, weighted by how often the board's
                                              mods call each symbol, from 0 to 1
    }

ledger/inputs/wasm.json  (crates/wasm, from milestone M3)
    {"schema": 1, "commit": "<40 hex chars>", "raw_bytes": 5012345,
     "gzip_bytes": 1834567, "budget_gzip_bytes": 4194304}

ledger/inputs/perf.json  (CLI timings in the nightly from M2, browser timings from M3)
    {
      "schema": 1,
      "date": "2026-11-04",
      "surfaces": [
        {"surface": "cli", "machine": "GitHub ubuntu-latest", "samples": 1000,
         "classify_ms_median": 41, "convert_ms_median": 1830}
      ]                                       "surface" is "cli" or "wasm"
    }

ledger/inputs/contributors.json  (tools/contributors.py --ledger, nightly contributors workflow)
    {
      "schema": 1,
      "as_of": "2026-11-03",                  last day of the window (UTC)
      "window_days": 30,
      "sources": ["git", "github-pulls"],     "github-pulls": merged PR authors were read
      "contributors_30d": {                   bots are never counted
        "people": {"count": 1, "logins": ["MosheByte"]},
        "agents": {"count": 1, "names": ["Claude Opus 5.5"]}
      },
      "first_time_contributors_30d": {"count": 0, "logins": []}
    }                                         null when the merged-PR lookup was unavailable;
                                              every count equals the length of its list

An area is listed under "What works" only when the harness measured it and at least 95%
of the measured mods are green (WORKS_THRESHOLD). Anything measured below that, or not
measured at all, is "Partial"; areas with an "unsupported" reason are "Unsupported".
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from fractions import Fraction
from pathlib import Path
from typing import Any

HEADER = "<!-- Generated by tools/ledger.py from ledger/inputs/. Do not edit by hand. -->"
INPUT_DIR = Path("ledger") / "inputs"
OUTPUT = "LEDGER.md"
SCHEMA = 1
WORKS_THRESHOLD = Fraction(95, 100)
MAX_RED_REASONS = 50
MAX_NAMES = 30
NO_NIGHTLY = "No nightly has run yet."
NO_DATA = "No data yet"

_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
_SHA = re.compile(r"^[0-9a-f]{40}$")


class LedgerInputError(ValueError):
    """An input file under ledger/inputs/ is malformed."""


# --------------------------------------------------------------------------- validation


class _Reader:
    """Typed access to one JSON object, with errors that name the file and the key."""

    def __init__(self, source: str, value: Any, where: str = "") -> None:
        self.source = source
        self.where = where
        if not isinstance(value, dict):
            raise self.error("must be a JSON object")
        self.value: dict[str, Any] = value
        self.used: set[str] = set()

    def error(self, message: str, key: str | None = None) -> LedgerInputError:
        path = self.where + (f".{key}" if key else "")
        location = f"{self.source}{':' if path else ''}{path.lstrip('.')}"
        return LedgerInputError(f"{location} {message}")

    def _get(self, key: str, required: bool = True) -> Any:
        self.used.add(key)
        if key not in self.value:
            if required:
                raise self.error("is required", key)
            return None
        return self.value[key]

    def count(self, key: str) -> int:
        value = self._get(key)
        if isinstance(value, bool) or not isinstance(value, int) or value < 0:
            raise self.error("must be a non-negative integer", key)
        return value

    def text(self, key: str, pattern: re.Pattern[str] | None = None) -> str:
        value = self._get(key)
        if not isinstance(value, str) or not value.strip():
            raise self.error("must be a non-empty string", key)
        if pattern is not None and not pattern.match(value):
            raise self.error(f"must match {pattern.pattern}", key)
        return value

    def optional_text(self, key: str) -> str | None:
        value = self._get(key, required=False)
        if value is None:
            return None
        if not isinstance(value, str) or not value.strip():
            raise self.error("must be null or a non-empty string", key)
        return value

    def share(self, key: str) -> float:
        value = self._get(key)
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise self.error("must be a number from 0 to 1", key)
        if not 0 <= value <= 1:
            raise self.error("must be a number from 0 to 1", key)
        return float(value)

    def texts(self, key: str) -> list[str]:
        value = self._get(key)
        if not isinstance(value, list) or not all(
            isinstance(v, str) and v.strip() for v in value
        ):
            raise self.error("must be a list of non-empty strings", key)
        return list(value)

    def objects(self, key: str) -> list[_Reader]:
        value = self._get(key)
        if not isinstance(value, list):
            raise self.error("must be a list", key)
        return [
            _Reader(self.source, item, f"{self.where}.{key}[{i}]")
            for i, item in enumerate(value)
        ]

    def child(self, key: str) -> _Reader:
        return _Reader(self.source, self._get(key), f"{self.where}.{key}")

    def optional_child(self, key: str) -> _Reader | None:
        value = self._get(key)
        return None if value is None else _Reader(self.source, value, f"{self.where}.{key}")

    def schema(self) -> None:
        value = self._get("schema")
        if value != SCHEMA or isinstance(value, bool):
            raise self.error(f"must be {SCHEMA}", "schema")

    def done(self) -> None:
        unknown = sorted(set(self.value) - self.used)
        if unknown:
            raise self.error("has unknown keys: " + ", ".join(unknown))


def _load(root: Path, name: str) -> _Reader | None:
    path = root / INPUT_DIR / name
    if not path.is_file():
        return None
    source = (INPUT_DIR / name).as_posix()
    try:
        data = json.loads(path.read_bytes().decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as err:
        raise LedgerInputError(f"{source} is not valid UTF-8 JSON: {err}") from err
    reader = _Reader(source, data)
    reader.schema()
    return reader


def _board(r: _Reader) -> dict[str, Any]:
    board: dict[str, Any] = {
        "run": r.text("run"),
        "date": r.text("date", _DATE),
        "commit": r.text("commit", _SHA),
        "game_versions": r.texts("game_versions"),
        "mods": r.count("mods"),
        "green": r.count("green"),
        "yellow": r.count("yellow"),
        "red": r.count("red"),
        "not_run": r.count("not_run"),
    }
    total = board["green"] + board["yellow"] + board["red"] + board["not_run"]
    if total != board["mods"]:
        raise r.error(
            f"green + yellow + red + not_run is {total}, but mods is {board['mods']}"
        )
    harness = r.child("harness")
    board["completed"] = harness.count("completed")
    board["attempted"] = harness.count("attempted")
    harness.done()
    if board["completed"] > board["attempted"]:
        raise harness.error("completed exceeds attempted")
    areas = []
    seen: set[str] = set()
    for a in r.objects("areas"):
        area = {
            "area": a.text("area"),
            "measured": a.count("measured"),
            "green": a.count("green"),
            "unsupported": a.optional_text("unsupported"),
        }
        a.done()
        if area["green"] > area["measured"]:
            raise a.error("green exceeds measured")
        if area["area"] in seen:
            raise a.error(f"repeats area {area['area']!r}")
        seen.add(area["area"])
        areas.append(area)
    board["areas"] = sorted(areas, key=lambda a: a["area"])
    reasons = []
    seen = set()
    for item in r.objects("red_reasons"):
        reason = {"reason": item.text("reason"), "count": item.count("count")}
        item.done()
        if reason["reason"] in seen:
            raise item.error(f"repeats reason {reason['reason']!r}")
        seen.add(reason["reason"])
        reasons.append(reason)
    classified = sum(x["count"] for x in reasons)
    if classified > board["red"]:
        raise r.error(f"red_reasons count {classified} red mods, but red is {board['red']}")
    board["red_reasons"] = sorted(reasons, key=lambda x: (-x["count"], x["reason"]))
    r.done()
    return board


def _coverage(r: _Reader) -> dict[str, Any]:
    cov: dict[str, Any] = {"date": r.text("date", _DATE)}
    versions = []
    for v in r.objects("versions"):
        version = {
            "game_version": v.text("game_version"),
            "fabric_api": v.text("fabric_api"),
            "symbols": v.count("symbols"),
            "with_rule": v.count("with_rule"),
            "tier_b": v.count("tier_b"),
            "unsupported": v.count("unsupported"),
            "weighted": v.share("weighted"),
        }
        v.done()
        mapped = version["with_rule"] + version["tier_b"] + version["unsupported"]
        if mapped > version["symbols"]:
            raise v.error(f"with_rule + tier_b + unsupported is {mapped}, above symbols")
        versions.append(version)
    cov["versions"] = sorted(versions, key=lambda v: v["game_version"])
    r.done()
    return cov


def _wasm(r: _Reader) -> dict[str, Any]:
    wasm = {
        "commit": r.text("commit", _SHA),
        "raw_bytes": r.count("raw_bytes"),
        "gzip_bytes": r.count("gzip_bytes"),
        "budget_gzip_bytes": r.count("budget_gzip_bytes"),
    }
    r.done()
    return wasm


def _perf(r: _Reader) -> dict[str, Any]:
    perf: dict[str, Any] = {"date": r.text("date", _DATE)}
    surfaces = []
    for s in r.objects("surfaces"):
        surface = {
            "surface": s.text("surface"),
            "machine": s.text("machine"),
            "samples": s.count("samples"),
            "classify_ms_median": s.count("classify_ms_median"),
            "convert_ms_median": s.count("convert_ms_median"),
        }
        s.done()
        if surface["surface"] not in ("cli", "wasm"):
            raise s.error('must name surface "cli" or "wasm"', "surface")
        surfaces.append(surface)
    perf["surfaces"] = sorted(surfaces, key=lambda s: s["surface"])
    r.done()
    return perf


def _named(r: _Reader, key: str) -> list[str]:
    """{"count": n, key: [...]}: n distinct names."""
    count = r.count("count")
    names = r.texts(key)
    r.done()
    if len(set(names)) != len(names):
        raise r.error("repeats a name", key)
    if count != len(names):
        raise r.error(f"count is {count}, but {key} has {len(names)}")
    return names


def _contributors(r: _Reader) -> dict[str, Any]:
    data: dict[str, Any] = {
        "as_of": r.text("as_of", _DATE),
        "window_days": r.count("window_days"),
        "sources": r.texts("sources"),
    }
    unknown = sorted(set(data["sources"]) - {"git", "github-pulls"})
    if unknown:
        raise r.error("names unknown sources: " + ", ".join(unknown), "sources")
    c = r.child("contributors_30d")
    data["people"] = _named(c.child("people"), "logins")
    data["agents"] = _named(c.child("agents"), "names")
    c.done()
    first = r.optional_child("first_time_contributors_30d")
    data["first_time"] = None if first is None else _named(first, "logins")
    r.done()
    return data


def load_inputs(root: Path) -> dict[str, dict[str, Any] | None]:
    """Reads and validates every input under ROOT/ledger/inputs/. Missing files are None."""
    loaders = {
        "board": ("board-summary.json", _board),
        "coverage": ("coverage.json", _coverage),
        "wasm": ("wasm.json", _wasm),
        "perf": ("perf.json", _perf),
        "contributors": ("contributors.json", _contributors),
    }
    inputs: dict[str, dict[str, Any] | None] = {}
    for key, (name, parse) in loaders.items():
        reader = _load(root, name)
        inputs[key] = None if reader is None else parse(reader)
    return inputs


