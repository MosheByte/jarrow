//! Access and property flags (JVMS tables 4.1-B, 4.5-A, 4.6-A and 4.7.6-A).
//!
//! Flags are plain `u16` values in [`crate::ClassFile`], [`crate::Field`] and
//! [`crate::Method`]. Several bits mean different things in different places (0x0020 is
//! `ACC_SUPER` on a class and `ACC_SYNCHRONIZED` on a method), so each constant says
//! where it applies.

/// Class, field, method, inner class: declared `public`.
pub const PUBLIC: u16 = 0x0001;
/// Field, method, inner class: declared `private`.
pub const PRIVATE: u16 = 0x0002;
/// Field, method, inner class: declared `protected`.
pub const PROTECTED: u16 = 0x0004;
/// Field, method, inner class: declared `static`.
pub const STATIC: u16 = 0x0008;
/// Class, field, method, inner class, parameter: declared `final`.
pub const FINAL: u16 = 0x0010;
/// Class: treat superclass methods specially in `invokespecial` (always set by modern compilers).
pub const SUPER: u16 = 0x0020;
/// Method: declared `synchronized`.
pub const SYNCHRONIZED: u16 = 0x0020;
/// Field: declared `volatile`.
pub const VOLATILE: u16 = 0x0040;
/// Method: a bridge method generated by the compiler.
pub const BRIDGE: u16 = 0x0040;
/// Field: declared `transient`.
pub const TRANSIENT: u16 = 0x0080;
/// Method: declared with variable arity.
pub const VARARGS: u16 = 0x0080;
/// Method: declared `native`.
pub const NATIVE: u16 = 0x0100;
/// Class, inner class: an interface.
pub const INTERFACE: u16 = 0x0200;
/// Class, method, inner class: declared `abstract`.
pub const ABSTRACT: u16 = 0x0400;
/// Method: declared `strictfp` (class files before version 61).
pub const STRICT: u16 = 0x0800;
/// Class, field, method, inner class, parameter: not present in source.
pub const SYNTHETIC: u16 = 0x1000;
/// Class, inner class: an annotation interface.
pub const ANNOTATION: u16 = 0x2000;
/// Class, field, inner class: an enum class or enum constant.
pub const ENUM: u16 = 0x4000;
/// Parameter: implicitly declared in source (a mandated parameter).
pub const MANDATED: u16 = 0x8000;
/// Class: a module descriptor (`module-info.class`).
pub const MODULE: u16 = 0x8000;
